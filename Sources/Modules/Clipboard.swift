import AppKit
import Combine
import Foundation

/// Smart Clipboard: история скопированного текста и картинок + скриншоты.
/// Всё хранится только на этом Mac (Application Support/MacIsland/Clipboard).
/// Пароли не попадают: менеджеры паролей помечают их типом ConcealedType, такие копирования пропускаем.
@MainActor
final class ClipboardStore: ObservableObject {
    static let shared = ClipboardStore()

    struct Item: Identifiable, Codable, Equatable {
        enum Kind: String, Codable { case text, image }
        var id = UUID()
        var kind: Kind
        var text: String?
        var file: String?            // имя png в папке истории (для картинок)
        var isScreenshot = false
        var date = Date()
        var pinned = false
    }

    @Published private(set) var texts: [Item] = []
    @Published private(set) var images: [Item] = []
    let copied = PassthroughSubject<Item, Never>()

    private let settings = AppSettings.shared
    private var lastChange = NSPasteboard.general.changeCount
    private var timer: Timer?
    private var seenScreenshots = Set<String>()
    private var started = Date()
    private var bag = Set<AnyCancellable>()

    static let dir: URL = {
        let d = AppInfo.supportDir.appendingPathComponent("Clipboard", isDirectory: true)
        try? FileManager.default.createDirectory(at: d, withIntermediateDirectories: true)
        return d
    }()
    private static var historyFile: URL { dir.appendingPathComponent("history.json") }

    /// Менеджеры паролей и связка ключей — их не запоминаем никогда.
    private let excludedApps: Set<String> = [
        "com.apple.keychainaccess", "com.apple.Passwords", "com.1password.1password", "com.agilebits.onepassword7",
        "com.bitwarden.desktop", "com.lastpass.LastPass", "com.dashlane.dashlanephonefinal", "in.sinew.Enpass-Desktop",
        "com.keepassxc.keepassxc", "org.keepassxc.keepassxc",
    ]

    var isEmpty: Bool { texts.isEmpty && images.isEmpty }

    func url(for item: Item) -> URL? { item.file.map { Self.dir.appendingPathComponent($0) } }
    func image(for item: Item) -> NSImage? { url(for: item).flatMap { NSImage(contentsOf: $0) } }

    func start() {
        load()
        started = Date()
        let t = Timer(timeInterval: 0.5, repeats: true) { [weak self] _ in MainActor.assumeIsolated { self?.poll() } }
        RunLoop.main.add(t, forMode: .common)
        timer = t
        settings.$clipboardScreenshots.removeDuplicates()
            .sink { [weak self] on in DispatchQueue.main.async { MainActor.assumeIsolated { self?.watchScreenshots(on) } } }
            .store(in: &bag)
    }

    // MARK: Буфер обмена

    private func poll() {
        let pb = NSPasteboard.general
        guard pb.changeCount != lastChange else { return }
        lastChange = pb.changeCount
        guard settings.clipboardEnabled else { return }

        let types = Set((pb.types ?? []).map(\.rawValue))
        let secret = ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
                      "org.nspasteboard.AutoGeneratedType", "com.agilebits.onepassword"]
        if secret.contains(where: types.contains) { return }
        if let app = NSWorkspace.shared.frontmostApplication?.bundleIdentifier, excludedApps.contains(app) { return }

        // Скопировали файлы в Finder — это не текст и не картинка, пропускаем
        if types.contains("public.file-url") { return }
        let hasImage = types.contains(NSPasteboard.PasteboardType.png.rawValue)
            || types.contains(NSPasteboard.PasteboardType.tiff.rawValue)
        if hasImage, let data = pb.data(forType: .png) ?? pb.data(forType: .tiff) {
            addImage(data, screenshot: false)      // картинка из браузера или скриншот в буфер (⌃⇧⌘4)
        } else if let s = pb.string(forType: .string) {
            addText(s)
        }
    }

    private func addText(_ raw: String) {
        let s = raw.trimmingCharacters(in: .whitespacesAndNewlines)
        guard !s.isEmpty, s.count <= 20_000 else { return }
        var item = Item(kind: .text, text: s)
        if let i = texts.firstIndex(where: { $0.text == s }) {
            item = texts.remove(at: i)
            item.date = Date()
        }
        texts.insert(item, at: 0)
        trim()
        save()
        copied.send(item)
    }

    private func addImage(_ data: Data, screenshot: Bool) {
        guard let rep = NSBitmapImageRep(data: data),
              let png = rep.representation(using: .png, properties: [:]) else { return }
        let name = UUID().uuidString + ".png"
        do { try png.write(to: Self.dir.appendingPathComponent(name)) } catch { return }
        let item = Item(kind: .image, file: name, isScreenshot: screenshot)
        images.insert(item, at: 0)
        trim()
        save()
        copied.send(item)
    }

    /// Лишние (самые старые незакреплённые) удаляем, когда превышен лимит.
    private func trim() {
        func cut(_ list: inout [Item], limit: Int) {
            while list.count > max(limit, list.filter(\.pinned).count),
                  let i = list.lastIndex(where: { !$0.pinned }) {
                removeFile(list[i])
                list.remove(at: i)
            }
        }
        cut(&texts, limit: settings.clipboardTextLimit)
        cut(&images, limit: settings.clipboardImageLimit)
    }

    // MARK: Действия

    /// Положить элемент обратно в буфер обмена.
    func copy(_ item: Item) {
        let pb = NSPasteboard.general
        pb.clearContents()
        switch item.kind {
        case .text: pb.setString(item.text ?? "", forType: .string)
        case .image:
            if let img = image(for: item) { pb.writeObjects([img]) }
        }
        lastChange = pb.changeCount          // это мы сами — в историю не добавляем
    }

    func copyText(_ s: String) {
        let pb = NSPasteboard.general
        pb.clearContents()
        pb.setString(s, forType: .string)
        lastChange = pb.changeCount
    }

    func togglePin(_ item: Item) {
        if let i = texts.firstIndex(where: { $0.id == item.id }) { texts[i].pinned.toggle() }
        if let i = images.firstIndex(where: { $0.id == item.id }) { images[i].pinned.toggle() }
        trim(); save()
    }

    func delete(_ item: Item) {
        texts.removeAll { $0.id == item.id }
        if let i = images.firstIndex(where: { $0.id == item.id }) { removeFile(images[i]); images.remove(at: i) }
        save()
    }

    /// Очистить историю. Закреплённое остаётся, если не попросили всё.
    func clear(includingPinned: Bool = false) {
        for it in images where includingPinned || !it.pinned { removeFile(it) }
        texts.removeAll { includingPinned || !$0.pinned }
        images.removeAll { includingPinned || !$0.pinned }
        save()
    }

    private func removeFile(_ item: Item) {
        if let u = url(for: item) { try? FileManager.default.removeItem(at: u) }
    }

    // MARK: Скриншоты
    // Spotlight не отдаёт программе файлы с Рабочего стола, пока ей не разрешён доступ к этой папке,
    // поэтому следим за папкой скриншотов сами. Первое обращение вызывает системный запрос доступа.
    // Скриншот узнаём по метке, которую macOS ставит на такие файлы (kMDItemIsScreenCapture).

    private var dirSource: DispatchSourceFileSystemObject?

    static var screenshotFolder: URL {
        let custom = UserDefaults(suiteName: "com.apple.screencapture")?.string(forKey: "location")
        if let c = custom, !c.isEmpty {
            return URL(fileURLWithPath: (c as NSString).expandingTildeInPath, isDirectory: true)
        }
        return FileManager.default.homeDirectoryForCurrentUser.appendingPathComponent("Desktop", isDirectory: true)
    }

    private func watchScreenshots(_ on: Bool) {
        dirSource?.cancel()
        dirSource = nil
        guard on else { return }
        let dir = Self.screenshotFolder
        // Первое обращение к папке вызывает системный запрос доступа и ждёт ответа —
        // делаем это в фоне, чтобы остров не «замерзал», пока запрос висит на экране.
        DispatchQueue.global(qos: .utility).async { [weak self] in
            let existing = (try? FileManager.default.contentsOfDirectory(atPath: dir.path)) ?? []
            let fd = open(dir.path, O_EVTONLY)
            DispatchQueue.main.async {
                MainActor.assumeIsolated {
                    guard let self else { return }
                    for name in existing { self.seenScreenshots.insert(dir.appendingPathComponent(name).path) }
                    guard fd >= 0 else { return }
                    let src = DispatchSource.makeFileSystemObjectSource(fileDescriptor: fd, eventMask: [.write, .rename], queue: .main)
                    src.setEventHandler { [weak self] in
                        // Метку «скриншот» macOS дописывает чуть позже самого файла — даём ей секунду
                        DispatchQueue.main.asyncAfter(deadline: .now() + 0.8) { MainActor.assumeIsolated { self?.scanScreenshots() } }
                    }
                    src.setCancelHandler { close(fd) }
                    src.resume()
                    self.dirSource = src
                }
            }
        }
    }

    private func scanScreenshots() {
        guard settings.clipboardEnabled, settings.clipboardScreenshots else { return }
        let dir = Self.screenshotFolder
        let seen = seenScreenshots
        let since = started.addingTimeInterval(-5)
        DispatchQueue.global(qos: .utility).async { [weak self] in
            let files = (try? FileManager.default.contentsOfDirectory(at: dir, includingPropertiesForKeys: [.creationDateKey])) ?? []
            var found: [(path: String, data: Data?)] = []
            for u in files where !seen.contains(u.path) {
                guard ["png", "jpg", "jpeg", "heic", "tiff"].contains(u.pathExtension.lowercased()),
                      Self.isScreenshot(u) else { continue }       // ещё не помечен — проверим при следующем событии
                let created = (try? u.resourceValues(forKeys: [.creationDateKey]).creationDate) ?? .distantPast
                found.append((u.path, created > since ? try? Data(contentsOf: u) : nil))
            }
            DispatchQueue.main.async {
                MainActor.assumeIsolated {
                    guard let self else { return }
                    for f in found where !self.seenScreenshots.contains(f.path) {
                        self.seenScreenshots.insert(f.path)
                        if let d = f.data { self.addImage(d, screenshot: true) }
                    }
                }
            }
        }
    }

    nonisolated static func isScreenshot(_ url: URL) -> Bool {
        getxattr(url.path, "com.apple.metadata:kMDItemIsScreenCapture", nil, 0, 0, 0) > 0
    }

    // MARK: Хранение

    private func save() {
        let all = texts + images
        if let d = try? JSONEncoder().encode(all) { try? d.write(to: Self.historyFile, options: .atomic) }
    }

    private func load() {
        guard let d = try? Data(contentsOf: Self.historyFile),
              let all = try? JSONDecoder().decode([Item].self, from: d) else { return }
        texts = all.filter { $0.kind == .text }
        images = all.filter { $0.kind == .image && url(for: $0).map { FileManager.default.fileExists(atPath: $0.path) } == true }
    }

    func debugAdd(text: String) { addText(text) }
    func debugAdd(image: Data, screenshot: Bool) { addImage(image, screenshot: screenshot) }
}
